export type BiText = typeof translations.zh;

export function biText(language: Language): BiText {
  return language === "en" ? translations.en : translations.zh;
}

export function fill(template: string, vars: Record<string, string | number>): string {
  return template.replace(/\{(\w+)\}/g, (_, k) => (vars[k] == null ? "" : String(vars[k])));
}

export function sourceLabel(t: BiText, source: string): string {
  const map: Record<string, string> = {
    web: t.srcWeb,
    cli: t.srcCli,
    mcp: t.srcMcp,
    github: t.srcGithub,
    token: t.srcToken,
    api: t.srcApi
  };
  return map[source] || source;
}
